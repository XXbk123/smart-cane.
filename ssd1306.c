static HAL_StatusTypeDef wr_cmd(uint8_t cmd)
{
  uint8_t data[2] = {0x00, cmd};
  return HAL_I2C_Master_Transmit(g_hi2c, SSD1306_I2C_ADDR, data, 2, 100);
}

static HAL_StatusTypeDef wr_data(const uint8_t *p, uint16_t n)
{
  /* control 0x40 + payload; send in chunks to stay under HAL buffer comfort */
  uint8_t packet[17];
  while (n) {
    uint16_t chunk = (n > 16) ? 16 : n;
    packet[0] = 0x40;
    memcpy(&packet[1], p, chunk);
    if (HAL_I2C_Master_Transmit(g_hi2c, SSD1306_I2C_ADDR, packet, chunk + 1, 100) != HAL_OK) {
      return HAL_ERROR;
    }
    p += chunk;
    n -= chunk;
  }
  return HAL_OK;
}

int SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
  g_hi2c = hi2c;
  memset(g_buf, 0, sizeof(g_buf));

  if (HAL_I2C_IsDeviceReady(g_hi2c, SSD1306_I2C_ADDR, 3, 100) != HAL_OK) {
    return -1;
  }

  HAL_Delay(50);

  wr_cmd(0xAE); /* display off */
  wr_cmd(0xD5); wr_cmd(0x80);
  wr_cmd(0xA8); wr_cmd(0x3F);
  wr_cmd(0xD3); wr_cmd(0x00);
  wr_cmd(0x40);
  wr_cmd(0x8D); wr_cmd(0x14); /* charge pump on */
  wr_cmd(0x20); wr_cmd(0x00); /* horizontal addressing */
  wr_cmd(0xA1); /* segment remap */
  wr_cmd(0xC8); /* COM scan dec */
  wr_cmd(0xDA); wr_cmd(0x12);
  wr_cmd(0x81); wr_cmd(0xCF);
  wr_cmd(0xD9); wr_cmd(0xF1);
  wr_cmd(0xDB); wr_cmd(0x40);
  wr_cmd(0xA4);
  wr_cmd(0xA6);
  wr_cmd(0xAF); /* display on */

  SSD1306_Clear();
  SSD1306_UpdateScreen();
  return 0;
}

void SSD1306_Clear(void)
{
  memset(g_buf, 0, sizeof(g_buf));
}

void SSD1306_SetPixel(uint8_t x, uint8_t y, uint8_t on)
{
  if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;
  if (on) {
    g_buf[x + (y / 8) * SSD1306_WIDTH] |=  (1 << (y & 7));
  } else {
    g_buf[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y & 7));
  }
}

void SSD1306_UpdateScreen(void)
{
  if (!g_hi2c) return;
  wr_cmd(0x21); wr_cmd(0); wr_cmd(127); /* column */
  wr_cmd(0x22); wr_cmd(0); wr_cmd(7);    /* page */
  wr_data(g_buf, sizeof(g_buf));
}

void SSD1306_DrawChar(uint8_t x, uint8_t y, char c)
{
  if (c < 0x20 || c > 0x7E) c = '?';
  const uint8_t *g = Font5x7[c - 0x20];
  for (uint8_t col = 0; col < 5; col++) {
    uint8_t line = g[col];
    for (uint8_t row = 0; row < 7; row++) {
      SSD1306_SetPixel((uint8_t)(x + col), (uint8_t)(y + row), (line >> row) & 1);
    }
  }
}

void SSD1306_DrawString(uint8_t x, uint8_t y, const char *s)
{
  while (s && *s) {
    if (x > SSD1306_WIDTH - 6) break;
    SSD1306_DrawChar(x, y, *s++);
    x = (uint8_t)(x + 6);
  }
}